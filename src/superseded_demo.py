"""Instruction 7 demo: what happens when the answer changed between circular versions.

For each version-sensitive question, run the same pipeline twice:
  naive    : version_mode="none"    (retrieval ignores document status)
  versioned: version_mode="current" (default pipeline)
and record which chunks were retrieved / cited and the answers.

  python src/superseded_demo.py                 # retrieval + answers, writes results/superseded_demo.md
  python src/superseded_demo.py --no-llm        # retrieval only, prints to the terminal, writes nothing
"""
import sys

import config as C
from retrieve import Retriever
from tables import md_table, text_table

QUESTIONS = [
    ("Current question, answer changed 2022 -> 2025",
     "Can a digital lender process borrower data on servers outside India?"),
    ("Current question, limit changed 2022 -> 2023 -> 2026",
     "What is the maximum amount for which a recurring credit card bill payment e-mandate can run without additional factor of authentication?"),
    ("Current question, rule moved from the 2023 DLG guidelines into the 2025 Directions",
     "What is the cap on default loss guarantee in digital lending?"),
    ("Explicitly historical question (old text is allowed, must be labelled)",
     "How did the data storage requirement for digital lending change from the 2022 guidelines to the current rules?"),
    ("Superseded document whose successor is NOT in the corpus",
     "How often must banks carry out periodic KYC updation for high-risk customers?"),
]
MODES = [("none", "Naive (no version policy)"), ("current", "Versioned pipeline (default)")]
CHUNK_HEADERS = ["#", "Chunk", "Status", "Issued", "Document", "Section"]


def chunk_rows(res):
    return [[c["rank"], c["chunk_id"], c["status"], c["issue_date"], c["doc_title"][:60], c["section_heading"][:45]]
            for c in res["results"]]


def main(use_llm=True):
    r = Retriever("B")
    r.search("warm up", method="hybrid")
    if use_llm:
        from generate import answer
    summary, body = [], []
    for n, (label, q) in enumerate(QUESTIONS, 1):
        body += [f"## {n}. {label}", "", f"**Question:** {q}", ""]
        row = [n, q[:70] + ("..." if len(q) > 70 else "")]
        for mode, tag in MODES:
            res = r.search(q, method="hybrid", version_mode=mode)
            n_sup = sum(c["status"] == "superseded" for c in res["results"])
            body += [f"### {tag}", "",
                     md_table(["Historical question detected", "Superseded chunks filtered", "Superseded chunks in top 5"],
                              [["yes" if res["historical"] else "no", "yes" if res["version_filtered"] else "no", n_sup]]),
                     "", md_table(CHUNK_HEADERS, chunk_rows(res), right=(0,)), ""]
            if use_llm:
                a = answer(q, res)
                sup = [c for c in a["citations"] if r.by_id[c]["status"] == "superseded"]
                body += [md_table(["Result", "Citations", "Superseded chunks cited"],
                                  [["declined" if a["refused"] else "answered", ", ".join(a["citations"]) or "-",
                                    ", ".join(sup) or "none"]]), "",
                         f"**{'Declined' if a['refused'] else 'Answer'}:** {a['refusal_reason'] if a['refused'] else a['answer']}", ""]
                row.append("declined" if a["refused"] else ", ".join(a["citations"]) + (" (superseded)" if sup else ""))
            else:
                row.append(f"{n_sup} superseded in top 5")
        summary.append(row)
    sum_headers = ["#", "Question", "Naive pipeline " + ("cites" if use_llm else "retrieves"),
                   "Versioned pipeline " + ("cites" if use_llm else "retrieves")]
    print(text_table(sum_headers, summary, right=(0,)))
    if not use_llm:
        print("\nRetrieval only: results/superseded_demo.md was not changed.")
        return
    lines = ["# Superseded-circular handling demo", "",
             "Same question, same retriever (section chunks + hybrid), with and without the version policy.",
             f"Answers generated by `{C.GEN_MODEL}`.", "", "## Summary", "", md_table(sum_headers, summary, right=(0,)), ""] + body
    out = C.RESULTS / "superseded_demo.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main(use_llm="--no-llm" not in sys.argv)
